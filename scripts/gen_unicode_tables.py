#!/usr/bin/env python3
"""Generate libpanduck/include/panduck/unicode_tables.hpp from Python's unicodedata.

HeadingSlug (slugify.hpp) follows pandoc's auto_identifiers rule, which is written
in Haskell's Data.Char terms: toLower, isAlphaNum, isAlpha, isSpace. Those need
Unicode data. libpanduck may not use DuckDB's utf8proc, and a new library would need
a wasm build, so the data is generated here and committed (Teague, 2026-11-14).

  isAlpha    general category L*            -> ALPHA_RANGES
  isAlphaNum L* or N* (Nd, Nl, No)           -> ALNUM_RANGES
  isSpace    category Zs, or \\t \\n \\v \\f \\r -> SPACE_RANGES
  toLower    the SIMPLE lowercase mapping   -> LOWER_MAP

Python's str.lower() is the FULL mapping, which for U+0130 (İ) gives two code
points. Haskell's toLower is the simple one, U+0069; pandoc gives "istanbul". So
a code point whose full lowercase is longer than one character takes the simple
mapping from the special-case list below.

The Unicode version is Python's, recorded in the header. GHC's may differ for code
points added recently; the measured titles in test/sql/heading_ids.test pin the
cases that matter.

    python3 scripts/gen_unicode_tables.py
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "libpanduck" / "include" / "panduck" / "unicode_tables.hpp"

# Simple lowercase mappings where Python's full mapping has more than one code point.
SIMPLE_LOWER = {0x0130: 0x0069}


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def is_alpha(cp):
    return unicodedata.category(chr(cp)).startswith("L")


def is_alnum(cp):
    return unicodedata.category(chr(cp))[0] in "LN"


def is_space(cp):
    return cp in (0x09, 0x0A, 0x0B, 0x0C, 0x0D) or unicodedata.category(chr(cp)) == "Zs"


def lower_map():
    pairs = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        low = chr(cp).lower()
        if cp in SIMPLE_LOWER:
            pairs.append((cp, SIMPLE_LOWER[cp]))
        elif len(low) == 1 and ord(low) != cp:
            pairs.append((cp, ord(low)))
    return pairs


def emit_table(name, ctype, rows):
    # An INLINE FUNCTION WITH A FUNCTION-LOCAL STATIC, not a namespace-scope array:
    # libpanduck is C++11 (no inline variables), and a `static` array in a header
    # gives every translation unit its own copy. An inline function's static is one
    # object for the whole program.
    lines = [f"inline const {ctype} *{name}() {{", f"\tstatic const {ctype} table[] = {{"]
    for a, b in rows:
        lines.append(f"\t    {{0x{a:X}, 0x{b:X}}},")
    lines.append("\t};")
    lines.append("\treturn table;")
    lines.append("}")
    return "\n".join(lines)


def main():
    alpha = ranges(is_alpha)
    alnum = ranges(is_alnum)
    space = ranges(is_space)
    lower = lower_map()
    body = [
        "// GENERATED by scripts/gen_unicode_tables.py -- do not edit by hand.",
        f"// Unicode {unicodedata.unidata_version} (Python {sys.version.split()[0]}).",
        "// See that script for what each table means and why it exists.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace panduck {",
        "namespace unicode_tables {",
        "",
        "struct CodepointRange {",
        "\tuint32_t first;",
        "\tuint32_t last;",
        "};",
        "",
        "struct CodepointPair {",
        "\tuint32_t from;",
        "\tuint32_t to;",
        "};",
        "",
        "// clang-format off",
        emit_table("AlphaRanges", "CodepointRange", alpha),
        "",
        emit_table("AlnumRanges", "CodepointRange", alnum),
        "",
        emit_table("SpaceRanges", "CodepointRange", space),
        "",
        emit_table("LowerMap", "CodepointPair", lower),
        "// clang-format on",
        "",
        f"static const size_t ALPHA_RANGES_SIZE = {len(alpha)};",
        f"static const size_t ALNUM_RANGES_SIZE = {len(alnum)};",
        f"static const size_t SPACE_RANGES_SIZE = {len(space)};",
        f"static const size_t LOWER_MAP_SIZE = {len(lower)};",
        "",
        "} // namespace unicode_tables",
        "} // namespace panduck",
        "",
    ]
    OUT.write_text("\n".join(body), encoding="utf-8")
    print(f"wrote {OUT.name}: {len(alpha)} alpha, {len(alnum)} alnum, {len(space)} space ranges, {len(lower)} lower pairs")


if __name__ == "__main__":
    main()
