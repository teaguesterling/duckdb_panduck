//! Pandoc's heading identifier, shared by every reader that derives an anchor.
//!
//! WHY THIS IS ONE FUNCTION. textile and mediawiki each held a private copy that differed
//! only in separator, and the comments on both insisted the separator was a FORMAT
//! CONVENTION rather than a choice -- which was true, and which hid that both copies were
//! also wrong in the same three ways. Measured against pandoc 3.1.3, the copies kept
//! leading digits, trimmed a trailing connector, and had no fallback for a title with no
//! letters in it. One wrong function in two places reads as two independent decisions.
//!
//! THE RULE, measured rather than assumed -- every line below was probed against a real
//! pandoc, and the probes that turned out to measure a format's INLINE PARSER instead of
//! this rule were discarded rather than encoded:
//!
//!   alphanumeric     lowercased
//!   a RUN of spaces  collapses to ONE separator
//!   `-`              becomes the separator: `-` for rst/textile, `_` for mediawiki
//!   `_`              always literal `_`, whatever the separator is
//!   anything else    DROPPED, and never becomes a separator, so `Trailing bang!` is
//!                    `trailing-bang` with no dangling connector
//!   leading run      skipped up to the FIRST LETTER, so `2019 Annual Report` is
//!                    `annual-report` and `1. Real Title` is `real-title`
//!   nothing left     the literal `section`
//!
//! Runs of `-` and `_` are NOT collapsed, though runs of spaces are: `Mix-_-Mix` is
//! `mix-_-mix` with a hyphen separator and `mix___mix` with an underscore one. A trailing
//! connector SURVIVES -- `End With Hyphen-` is `end-with-hyphen-` -- which is the opposite
//! of what both previous copies did.
//!
//! THE INPUT IS RENDERED TEXT, not source. `**Bold** Title` must arrive as `Bold Title`, so
//! the delimiters contribute nothing to the anchor. Callers pass the flattened title.
//!
//! UNICODE, AS PANDOC DOES IT (2026-11-14). The rule above is pandoc's auto_identifiers
//! rule in Haskell Data.Char terms, and those terms are Unicode-wide: toLower maps `É`
//! to `é` and `Σ` to `σ`; isAlphaNum keeps letters and digits of any script (`日本`);
//! isSpace makes U+3000 a separator; everything else, `—`, an emoji, `«`, is dropped;
//! and the leading run is skipped up to the first Unicode LETTER, so `١٢٣ Arabic` is
//! `arabic`. `.` is kept, as `_` and `-` are: `Version 1.2 notes` is
//! `version-1.2-notes`. Measured against pandoc 3.1.3's markdown, rst, textile and
//! mediawiki readers, which agree (test/sql/heading_ids.test). The data is
//! unicode_tables.hpp, generated by scripts/gen_unicode_tables.py.
//!
//! Before this, bytes at or above 0x80 passed through as letters: `ÉCOLE` gave `École`
//! and `A — B` gave `a-—-b`. Teague ruled on 2026-11-14 that ids follow pandoc's rule
//! everywhere, which made those divergences defects.
namespace slug_detail {

inline bool InRanges(const unicode_tables::CodepointRange *table, size_t size, uint32_t cp) {
	size_t lo = 0, hi = size;
	while (lo < hi) {
		size_t mid = (lo + hi) / 2;
		if (cp < table[mid].first) {
			hi = mid;
		} else if (cp > table[mid].last) {
			lo = mid + 1;
		} else {
			return true;
		}
	}
	return false;
}

inline uint32_t ToLower(uint32_t cp) {
	if (cp < 0x80) {
		return static_cast<uint32_t>(std::tolower(static_cast<int>(cp)));
	}
	const unicode_tables::CodepointPair *map = unicode_tables::LowerMap();
	size_t lo = 0, hi = unicode_tables::LOWER_MAP_SIZE;
	while (lo < hi) {
		size_t mid = (lo + hi) / 2;
		if (cp < map[mid].from) {
			hi = mid;
		} else if (cp > map[mid].from) {
			lo = mid + 1;
		} else {
			return map[mid].to;
		}
	}
	return cp;
}

inline bool IsAlpha(uint32_t cp) {
	return InRanges(unicode_tables::AlphaRanges(), unicode_tables::ALPHA_RANGES_SIZE, cp);
}

inline bool IsAlnum(uint32_t cp) {
	return InRanges(unicode_tables::AlnumRanges(), unicode_tables::ALNUM_RANGES_SIZE, cp);
}

inline bool IsSpace(uint32_t cp) {
	return InRanges(unicode_tables::SpaceRanges(), unicode_tables::SPACE_RANGES_SIZE, cp);
}

//! One code point from UTF-8 at `i`, advancing `i`. A malformed or truncated sequence
//! yields U+FFFD for its first byte, which no table holds, so the slug drops it.
inline uint32_t Decode(const std::string &s, size_t &i) {
	unsigned char c = static_cast<unsigned char>(s[i++]);
	if (c < 0x80) {
		return c;
	}
	int extra = c >= 0xF0 ? 3 : c >= 0xE0 ? 2 : c >= 0xC0 ? 1 : -1;
	if (extra < 0 || i + static_cast<size_t>(extra) > s.size()) {
		return 0xFFFD;
	}
	uint32_t cp = c & (0x3F >> extra);
	for (int k = 0; k < extra; k++) {
		unsigned char cc = static_cast<unsigned char>(s[i]);
		if ((cc & 0xC0) != 0x80) {
			return 0xFFFD;
		}
		cp = (cp << 6) | (cc & 0x3F);
		i++;
	}
	return cp;
}

inline void Encode(uint32_t cp, std::string &out) {
	if (cp < 0x80) {
		out += static_cast<char>(cp);
	} else if (cp < 0x800) {
		out += static_cast<char>(0xC0 | (cp >> 6));
		out += static_cast<char>(0x80 | (cp & 0x3F));
	} else if (cp < 0x10000) {
		out += static_cast<char>(0xE0 | (cp >> 12));
		out += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
		out += static_cast<char>(0x80 | (cp & 0x3F));
	} else {
		out += static_cast<char>(0xF0 | (cp >> 18));
		out += static_cast<char>(0x80 | ((cp >> 12) & 0x3F));
		out += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
		out += static_cast<char>(0x80 | (cp & 0x3F));
	}
}

} // namespace slug_detail

inline std::string HeadingSlug(const std::string &text, char sep) {
	using namespace slug_detail;
	// pandoc's order: lowercase, keep alphanumerics and `_` `-` `.`, split on spaces
	// and join with the separator, then drop everything before the first letter.
	std::string out;
	bool started = false;       // have we reached the first letter yet?
	bool pending_space = false; // a space run is only worth a separator if something follows
	size_t i = 0;
	while (i < text.size()) {
		uint32_t cp = ToLower(Decode(text, i));
		if (IsSpace(cp)) {
			if (started) {
				pending_space = true;
			}
			continue;
		}
		const bool keep = IsAlnum(cp) || cp == '_' || cp == '-' || cp == '.';
		if (!keep) {
			// Dropped WITHOUT setting pending_space, so punctuation never leaves a
			// connector behind it.
			continue;
		}
		if (!started) {
			// The leading run up to the first LETTER goes, separators included.
			if (!IsAlpha(cp)) {
				continue;
			}
			started = true;
		}
		if (pending_space) {
			out += sep;
			pending_space = false;
		}
		if (cp == '-') {
			out += sep;
		} else {
			Encode(cp, out);
		}
	}
	// pandoc's fallback when the title contributes no identifier at all -- `123`, `!!! ???`.
	// Without this the anchor is the empty string, which no consumer can match on.
	return out.empty() ? std::string("section") : out;
}

//! A CLASS NAME from a source document's own label -- a DOCX or ODT paragraph style
//! name, a LaTeX environment -- for attributes['class'] (#182). Lowercased; every run
//! of characters that is not an ASCII letter or digit, a non-ASCII byte, or `_`
//! becomes one `-`; leading and trailing `-` are dropped. "Block Text" ->
//! "block-text", "Heading 1" -> "heading-1", "1st Para" -> "1st-para".
//!
//! NOT HeadingSlug, on purpose. An id follows pandoc's rule, which skips to the first
//! letter and falls back to `section`; a class does neither. A label that slugs to
//! nothing returns "", and the caller then sets no class.
inline std::string ClassSlug(const std::string &label) {
	std::string out;
	bool pending_sep = false;
	for (unsigned char c : label) {
		const bool keep = c >= 0x80 || std::isalnum(c) || c == '_';
		if (!keep) {
			pending_sep = !out.empty();
			continue;
		}
		if (pending_sep) {
			out += '-';
			pending_sep = false;
		}
		out += c >= 0x80 ? static_cast<char>(c) : static_cast<char>(std::tolower(c));
	}
	return out;
}

