#!/usr/bin/env python3
"""Regenerate heading_ids.test's shared-slug block from test/fixtures/slug_pandoc_cases.txt.

The fixture is shared by duckdb_markdown, webbed, dmb and panduck: one heading per line,
`title \\x01 pandoc-id`, each id measured with pandoc 3.1.3 (-f markdown-smart, one
heading per document). It is changed UPSTREAM, in duckdb_markdown's test/data/, and
copied here.

panduck's string readers take only literal arguments, so the test cannot read the titles
from the file at run time. This script writes the titles and ids into the test as
literals, and also writes a check that the literals EQUAL the file in both directions.
That check fails if the fixture is updated and this script is not re-run.

    cp <duckdb_markdown>/test/data/slug_pandoc_cases.txt test/fixtures/
    python3 scripts/sync_slug_cases.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "test" / "fixtures" / "slug_pandoc_cases.txt"
TEST = ROOT / "test" / "sql" / "heading_ids.test"
BEGIN = "# ---- BEGIN shared slug cases (generated by scripts/sync_slug_cases.py) ----"
END = "# ---- END shared slug cases ----"


def sql_str(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    rows = [line.rstrip("\n").split("\x01") for line in FIXTURE.read_text(encoding="utf-8").splitlines()]
    org = "\\n".join("* " + t.replace("\\", "\\\\").replace("'", "''") for t, _ in rows)
    values = ",\n    ".join(f"({sql_str(t)}, {sql_str(i)})" for t, i in rows)
    expected = "\n".join(i for _, i in rows)
    block = f"""{BEGIN}
# pandoc's identifier rule, character by character. Teague ruled on 2026-11-14 that ids
# follow pandoc's auto_identifiers rule in every reader and in markdown, webbed and dmb,
# and those four repos check this ONE list: test/fixtures/slug_pandoc_cases.txt, copied
# from duckdb_markdown's test/data/. {len(rows)} headings, each id measured with pandoc
# 3.1.3. One function (slugify.hpp HeadingSlug) serves every panduck reader, so the org
# string reader stands for all of them.

# The literals below ARE the shared file, in both directions. Re-run the script after
# copying a new fixture.
query I
SELECT count(*) FROM (
  SELECT title, id FROM read_csv('test/fixtures/slug_pandoc_cases.txt', delim = chr(1), header = false,
                                 quote = '', escape = '', columns = {{'title': 'VARCHAR', 'id': 'VARCHAR'}},
                                 strict_mode = false)
  EXCEPT
  SELECT * FROM (VALUES
    {values}) v(title, id)
) UNION ALL SELECT count(*) FROM (
  SELECT * FROM (VALUES
    {values}) v(title, id)
  EXCEPT
  SELECT title, id FROM read_csv('test/fixtures/slug_pandoc_cases.txt', delim = chr(1), header = false,
                                 quote = '', escape = '', columns = {{'title': 'VARCHAR', 'id': 'VARCHAR'}},
                                 strict_mode = false)
);
----
0
0

query I
SELECT attributes['id'] FROM read_org_blocks_string(E'{org}')
WHERE element_type = 'heading' ORDER BY element_order;
----
{expected}

{END}"""
    text = TEST.read_text(encoding="utf-8")
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        text = head + block + tail
    else:
        anchor = "# ---- the consumer:"
        text = text.replace(anchor, block + "\n\n" + anchor, 1)
    TEST.write_text(text, encoding="utf-8")
    print(f"wrote {len(rows)} shared slug cases into {TEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
